import 'dart:math';
import 'dart:typed_data';

import 'package:http/http.dart' as http;
import 'package:image/image.dart' as img;

import '../models/clothing_item.dart';
import '../models/outfit_result.dart';

class OutfitImageService {
  Future<Uint8List> composeOutfitImage({
    required OutfitResult result,
    String? title,
    bool cleanupBackground = true,
  }) async {
    final canvas = img.Image(width: 1200, height: 1600);
    img.fill(canvas, color: img.ColorRgb8(15, 15, 18));

    final top = await _prepareItemImage(result.top, cleanupBackground: cleanupBackground);
    final bottom = await _prepareItemImage(result.bottom, cleanupBackground: cleanupBackground);
    final shoes = await _prepareItemImage(result.shoes, cleanupBackground: cleanupBackground);
    final accessory = await _prepareItemImage(result.accessory, cleanupBackground: cleanupBackground);

    _drawSlot(canvas, x: 80, y: 120, w: 500, h: 580, itemImage: top);
    _drawSlot(canvas, x: 620, y: 120, w: 500, h: 580, itemImage: bottom);
    _drawSlot(canvas, x: 80, y: 760, w: 500, h: 500, itemImage: shoes);
    _drawSlot(canvas, x: 620, y: 760, w: 500, h: 500, itemImage: accessory);

    if ((title ?? '').trim().isNotEmpty) {
      img.drawString(
        canvas,
        (title!.length > 56 ? '${title.substring(0, 56)}...' : title),
        font: img.arial24,
        x: 90,
        y: 1330,
        color: img.ColorRgb8(245, 245, 245),
      );
    }

    img.drawString(
      canvas,
      'Generated by DLS Outfit Bot',
      font: img.arial14,
      x: 90,
      y: 1510,
      color: img.ColorRgb8(170, 170, 170),
    );

    return Uint8List.fromList(img.encodePng(canvas, level: 3));
  }

  Future<img.Image?> _prepareItemImage(
    ClothingItem? item, {
    required bool cleanupBackground,
  }) async {
    if (item == null || item.imageUrl.trim().isEmpty) {
      return null;
    }

    try {
      final response = await http.get(Uri.parse(item.imageUrl.trim()));
      if (response.statusCode < 200 || response.statusCode >= 300) {
        return null;
      }
      final decoded = img.decodeImage(response.bodyBytes);
      if (decoded == null) {
        return null;
      }
      final rgba = decoded.convert(numChannels: 4);
      if (!cleanupBackground) {
        return rgba;
      }
      return _removeFlatBackground(rgba);
    } catch (_) {
      return null;
    }
  }

  img.Image _removeFlatBackground(img.Image source) {
    final corners = <img.Color>[
      source.getPixel(0, 0),
      source.getPixel(max(source.width - 1, 0), 0),
      source.getPixel(0, max(source.height - 1, 0)),
      source.getPixel(max(source.width - 1, 0), max(source.height - 1, 0)),
    ];

    final avgR = corners.map((c) => c.r.toInt()).reduce((a, b) => a + b) ~/ corners.length;
    final avgG = corners.map((c) => c.g.toInt()).reduce((a, b) => a + b) ~/ corners.length;
    final avgB = corners.map((c) => c.b.toInt()).reduce((a, b) => a + b) ~/ corners.length;

    const threshold = 42;
    final out = source.clone();
    for (var y = 0; y < out.height; y++) {
      for (var x = 0; x < out.width; x++) {
        final px = out.getPixel(x, y);
        final distance = (px.r.toInt() - avgR).abs() +
            (px.g.toInt() - avgG).abs() +
            (px.b.toInt() - avgB).abs();
        if (distance < threshold) {
          out.setPixelRgba(x, y, px.r.toInt(), px.g.toInt(), px.b.toInt(), 0);
        }
      }
    }

    return out;
  }

  void _drawSlot(
    img.Image canvas, {
    required int x,
    required int y,
    required int w,
    required int h,
    required img.Image? itemImage,
  }) {
    final slotColor = img.ColorRgb8(30, 30, 34);
    img.fillRect(canvas, x1: x, y1: y, x2: x + w, y2: y + h, color: slotColor);

    if (itemImage == null) {
      return;
    }

    final fitted = _contain(itemImage, targetW: w - 40, targetH: h - 40);
    final dx = x + ((w - fitted.width) ~/ 2);
    final dy = y + ((h - fitted.height) ~/ 2);
    img.compositeImage(canvas, fitted, dstX: dx, dstY: dy, blend: img.BlendMode.alpha);
  }

  img.Image _contain(img.Image image, {required int targetW, required int targetH}) {
    final ratioW = targetW / image.width;
    final ratioH = targetH / image.height;
    final ratio = min(ratioW, ratioH);
    final nw = max(1, (image.width * ratio).round());
    final nh = max(1, (image.height * ratio).round());

    return img.copyResize(image, width: nw, height: nh, interpolation: img.Interpolation.average);
  }
}
